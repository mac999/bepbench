def normalise_locale(value: str | None) -> str:
    """Map anything user-supplied onto a supported locale code."""
    if not value:
        return DEFAULT_LOCALE
    code = str(value).strip().lower().replace("_", "-")
    if code in LOCALES:
        return code
    base = code.split("-", 1)[0]
    return base if base in LOCALES else DEFAULT_LOCALE


def get_locale() -> str:
    """Resolve the active locale: query string, then cookie, then browser."""
    try:
        from flask import has_request_context, request
    except ImportError:  # pragma: no cover - flask always present in practice
        return DEFAULT_LOCALE
    if not has_request_context():
        return DEFAULT_LOCALE
    if request.args.get("lang"):
        return normalise_locale(request.args.get("lang"))
    if request.cookies.get(COOKIE_NAME):
        return normalise_locale(request.cookies.get(COOKIE_NAME))
    best = request.accept_languages.best_match(list(LOCALES)) if request.accept_languages else None
    return normalise_locale(best)


def translate(key: str, locale: str | None = None, **kwargs: Any) -> str:
    """Look up ``key``; fall back to English, then to the key itself."""
    code = locale or get_locale()
    text = CATALOG.get(code, {}).get(key) or CATALOG[DEFAULT_LOCALE].get(key) or key
    return text.format(**kwargs) if kwargs else text


